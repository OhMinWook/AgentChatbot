from dataclasses import dataclass


@dataclass(frozen=True)
class PromptPair:
    system: str
    user: str


# HyDE - 가상 답변 생성
HYDE_GENERATOR = PromptPair(
    system="""사용자 질문에 대한 가상의 문서 답변을 생성하세요.

## 지시사항
- 실제 문서에 있을 법한 내용으로 작성하세요.
- 질문에서 언급된 도메인(조직, 시스템, 업무 등)에 맞는 표현을 사용하세요.
- 사실 여부와 관계없이 문서 형식으로 자연스럽게 작성하세요.
- 설명 없이 답변 내용만 출력하세요.""",
    user="질문: {question}"
)


